// Builds the standalone home-screen app (index.html + sw.js) from jade-mahjong.html,
// which is the page fragment published as the claude.ai artifact.
// Run: node build.js
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const dir = __dirname;

const src = fs.readFileSync(path.join(dir, 'jade-mahjong.html'), 'utf8');
const cut = src.indexOf('<header>');
if (cut < 0) throw new Error('jade-mahjong.html: <header> not found');
const head = src.slice(0, cut).trim();
const body = src.slice(cut).trim();

const index = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, user-scalable=no">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Mahjong">
<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="icon-180.png">
<link rel="icon" type="image/png" href="icon-192.png">
<style>
/* same base the artifact host provides */
html { box-sizing: border-box; overflow: hidden; background: #072a1f;
  padding-top: env(safe-area-inset-top, 0px); padding-bottom: env(safe-area-inset-bottom, 0px); }
body { margin: 0; font: 14px system-ui, -apple-system, sans-serif; }
img { max-width: 100%; }
[hidden] { display: none !important; }
</style>
${head}
</head>
<body>
${body}
<script>
if ('serviceWorker' in navigator) navigator.serviceWorker.register('sw.js').catch(() => {});
</script>
</body>
</html>
`;
fs.writeFileSync(path.join(dir, 'index.html'), index);

const version = crypto.createHash('sha1').update(index).digest('hex').slice(0, 10);
const sw = `// Generated by build.js. Network first so updates arrive when online; cache keeps the game playable offline.
const CACHE = 'jade-mahjong-${version}';
const FILES = ['./', 'index.html', 'manifest.webmanifest', 'icon-180.png', 'icon-192.png', 'icon-512.png'];
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(
    fetch(e.request).then(res => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); }
      return res;
    }).catch(() => caches.match(e.request, { ignoreSearch: true }).then(hit => hit || caches.match('index.html')))
  );
});
`;
fs.writeFileSync(path.join(dir, 'sw.js'), sw);
console.log('built index.html and sw.js, cache', version);
